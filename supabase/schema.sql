-- La política permite a cualquier usuario autenticado gestionar el directorio.
create table if not exists public.employees (
  id bigint generated by default as identity primary key,
  full_name text not null check (char_length(full_name) between 2 and 100),
  department text not null check (char_length(department) between 2 and 80),
  email text not null unique check (char_length(email) <= 150),
  created_at timestamptz not null default now()
);

alter table public.employees enable row level security;

drop policy if exists "Authenticated users can read employees" on public.employees;
create policy "Authenticated users can read employees"
on public.employees for select
to authenticated
using (true);

drop policy if exists "Authenticated users can add employees" on public.employees;
create policy "Authenticated users can add employees"
on public.employees for insert
to authenticated
with check (true);

drop policy if exists "Authenticated users can delete employees" on public.employees;
create policy "Authenticated users can delete employees"
on public.employees for delete
to authenticated
using (true);

grant select, insert, delete on public.employees to authenticated;
grant usage, select on sequence public.employees_id_seq to authenticated;
